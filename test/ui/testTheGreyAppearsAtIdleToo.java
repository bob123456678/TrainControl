    /**
     * A train's length changing regenerates the grey, with nothing running.
     *
     * Adam: *"...and be regenerated if a placement or train/track length is changed."*
     */
    @Test
    public void testATrainLengthChangeRegeneratesTheGreyAtIdle()
    {
        assertFalse(windowBlockedAtIdle.isEmpty(),
            "the window holds nothing blocked at idle even with the train standing, so there is no "
            + "grey for a length change to regenerate and this test measures nothing");

        assertTrue(windowBlockedAfterLengthZero.isEmpty(),
            "setting the train's length to zero - which is how this railway says \"not set\", and an "
            + "unmeasured train covers nothing - left the window still holding "
            + windowBlockedAfterLengthZero.size() + " squares blocked.  Nobody asked it to recompute "
            + "after the change, and nothing on the length door did either, so the diagram is greying "
            + "track that is no longer blocked");

        assertEquals(windowBlockedAfterLengthBack, windowBlockedAtIdle,
            "measuring the train again did not bring the grey back to what it was.  Taking a mark off "
            + "and putting it on are two halves of one gesture and only one of them was wired");
    }

    /**
     * A tile's length changing regenerates the grey, with nothing running.
     */
    @Test
    public void testATileLengthChangeRegeneratesTheGreyAtIdle()
    {
        assertTrue(theRebuildHappened,
            "the setup rebuild left the running Layout in place, so the tile lengths never reached "
            + "the railway and this test measured nothing.  `rebuildRunningLayoutFromSetup` is a "
            + "no-op without an active configuration, with autonomy busy, or with no viewer panel");

        // THE GESTURE MOVED THE RAILWAY'S OWN ANSWER, so the comparison below is not two copies of
        // one number.  Measuring every square as none shortens what a tail can reach - behaviour.md
        // 5c: the walk *"stops at unmeasured track.  Only positive lengths are determinate."*
        assertNotEquals(railwayBlockedWithTilesUnmeasured, railwayBlockedWithTilesMeasured,
            "the railway blocks exactly the same squares whether every tile measures one unit or "
            + "none, so writing tile lengths changed nothing and there is nothing for the diagram to "
            + "have followed.  Both answers: " + railwayBlockedWithTilesMeasured);

        assertFalse(railwayBlockedWithTilesMeasured.isEmpty(),
            "the railway blocks nothing at all once the track is measured again, so the standing "
            + "train did not survive the rebuild and this test is measuring an empty railway");

        assertEquals(windowBlockedWithTilesUnmeasured, railwayBlockedWithTilesUnmeasured,
            "after a tile-length change the diagram is greying "
            + windowBlockedWithTilesUnmeasured.size() + " squares and the railway is refusing "
            + railwayBlockedWithTilesUnmeasured.size() + ".  Nobody asked the window to recompute "
            + "after the setup rebuild, so the wash still describes the lengths before last");

        assertEquals(windowBlockedWithTilesMeasured, railwayBlockedWithTilesMeasured,
            "measuring the track again did not bring the grey back to what the railway refuses.  "
            + "Taking a mark off and putting it on are two halves of one gesture and only one of them "
            + "was wired");
    }

