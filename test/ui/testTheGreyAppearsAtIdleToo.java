    // ---------------------------------------------------------------- the gestures

    /**
     * Measures every square as none, rebuilds, and measures them as one again.
     *
     * A tile length can only reach the marks through a rebuild: edge lengths are baked into the built
     * `Layout` by `GraphReducer`, unlike train lengths, which `edgesCoveredByStandingTrains` reads off
     * the locomotive every time it is asked.  `rebuildRunningLayoutFromSetup` is exactly what
     * `AutonomyEditorPanel.setupChanged` posts once a length has been written.
     */
    private static void captureTheTileLengthGesture() throws Exception
    {
        Layout before = model.getAutoLayout();

        SwingUtilities.invokeAndWait(() -> measureEveryTileAs(0));

        SwingUtilities.invokeAndWait(() -> ui.rebuildRunningLayoutFromSetup());

        pump();
        pump();

        support.CoveredMarks.settle(ui);

        theRebuildHappened = model.getAutoLayout() != before;

        // The rebuild replaced the object; the railway's own answer has to be asked of the new one.
        layout = model.getAutoLayout();

        railwayBlockedWithTilesUnmeasured = blockedSquares();
        windowBlockedWithTilesUnmeasured = whatTheWindowHoldsBlocked();

        SwingUtilities.invokeAndWait(() -> measureEveryTileAs(1));

        SwingUtilities.invokeAndWait(() -> ui.rebuildRunningLayoutFromSetup());

        pump();
        pump();

        support.CoveredMarks.settle(ui);

        layout = model.getAutoLayout();

        railwayBlockedWithTilesMeasured = blockedSquares();
        windowBlockedWithTilesMeasured = whatTheWindowHoldsBlocked();
    }

    /**
     * Presses Delete over the square the train stands on, which is the diagram's own removal door.
     *
     * Delete rather than Control+X so that nothing lands on the clipboard, and rather than Control+V
     * so that no arrival-side dialog can open and block this on a modal.
     */
    private static void captureTheRemovalGesture() throws Exception
    {
        final TileKey square = squareOfTheStandingTrain();

        if (square == null)
        {
            windowBlockedAfterRemoval = new LinkedHashSet<>();

            throw new SkipException("the standing train's square cannot be named, so the diagram's"
                + " own Delete door cannot be aimed at it");
        }

        final Method gesture = TrainControlUI.class.getDeclaredMethod(
            "locomotiveGestureOnDiagram", int.class, boolean.class);

        gesture.setAccessible(true);

        final Object[] handled = new Object[1];

        SwingUtilities.invokeAndWait(() ->
        {
            try
            {
                ui.setHoveredDiagramTile(square.getPage(), square.getX(), square.getY());

                handled[0] = gesture.invoke(ui, KeyEvent.VK_DELETE, false);
            }
            catch (Exception refused)
            {
                handled[0] = refused;
            }
        });

        assertEquals(handled[0], Boolean.TRUE,
            "the diagram's Delete door declined the square the train is standing on (" + square
            + "), so nothing was removed and the claim below would pass by having changed nothing: "
            + handled[0]);

        pump();
        pump();

        // THE GESTURE ACTUALLY TOOK THE TRAIN OFF, asserted rather than assumed.  `true` is also what
        // this door returns when it REFUSES - autonomy busy, an editor open, no autonomy Point on the
        // square - each with a line in the log and nothing changed.  Without this, a refusal would
        // leave the grey exactly as it was and the claim below would report the diagram at fault.
        assertNull(squareOfTheStandingTrain(),
            "the train is still standing on the railway after the diagram's Delete door was pressed"
            + " over its square, so the door declined and nothing was removed");

        support.CoveredMarks.settle(ui);

        windowBlockedAfterRemoval = whatTheWindowHoldsBlocked();
    }

    /** The diagram square the one standing train is on, or null. */
    private static TileKey squareOfTheStandingTrain()
    {
        for (Point point : layout.getPoints())
        {
            if (point.getCurrentLocomotive() == null) continue;

            if (!point.getCurrentLocomotive().getName().equals(train.getName())) continue;

            TileKey square = session.getStationIndex() == null
                ? null : session.getStationIndex().squareOf(point.getName());

            if (square != null) return square;
        }

        return null;
    }

    // ---------------------------------------------------------------- what each side says

    /**
     * The squares the WINDOW is holding blocked, read off the cache the tiles are drawn from.
     *
     * Asked of every square the reduction knows, because there is no getter for the set itself and
     * `isTrackBlocked` is the question the tile asks.
     *
     * @return the blocked squares
     */
    private static Set<TileKey> whatTheWindowHoldsBlocked()
    {
        Set<TileKey> out = new LinkedHashSet<>();

        for (TileKey square : everyTile())
        {
            if (ui.isTrackBlocked(square)) out.add(square);
        }

        return out;
    }

    /**
     * The squares the RAILWAY holds blocked, worked out from the covered EDGES.
     *
     * Not asked of the window: the window is what is under test, and a test that asks it what the
     * answer is agrees with it whatever it says.  This is the translation `AutonomySession` performs -
     * a covered `Edge` runs between two `Point`s, each `Point` maps back to a square, and the reducer
     * holds the tiles lying between two squares - with the endpoints excluded, because a train
     * standing at a sensor is shown standing there and the points are technically unoccupied.
     *
     * @return the blocked squares
     */
    private static Set<TileKey> blockedSquares()
    {
        Set<TileKey> out = new LinkedHashSet<>();

        for (Edge edge : layout.edgesCoveredByStandingTrains().keySet())
        {
            if (edge == null || edge.getStart() == null || edge.getEnd() == null) continue;

            TileKey from = session.getStationIndex().squareOf(edge.getStart().getName());
            TileKey to = session.getStationIndex().squareOf(edge.getEnd().getName());

            if (from == null || to == null) continue;

            for (GraphReducer.ReducedEdge reduced : session.getReducer().getEdges())
            {
                boolean sameWay = from.equals(reduced.getStart()) && to.equals(reduced.getEnd());
                boolean otherWay = to.equals(reduced.getStart()) && from.equals(reduced.getEnd());

                if (!sameWay && !otherWay) continue;

                for (GraphReducer.TileStep step : reduced.getPath())
                {
                    if (step.getTile() == null) continue;

                    if (step.getTile().equals(from) || step.getTile().equals(to)) continue;

                    out.add(step.getTile());
                }

                break;
            }
        }

        return out;
    }

    /**
     * Finds a train length at which the railway blocks a square the train is not drawn on.
     *
     * Both marks have to be visible at once for any of this to be assertable, and how far each of them
     * reaches depends on the length: the line is as long as the train, the blocked extent is whole
     * edges.  A short train on a long edge separates them, and how short depends on the railway.
     *
     * @return true when all three squares were found
     */
    private static boolean chooseTheThreeSquares() throws Exception
    {
        for (int length = 1; length <= 6; length++)
        {
            train.setTrainLength(length);

            support.CoveredMarks.refresh(ui);

            pump();

            Set<TileKey> blocked = blockedSquares();

            TileKey onTheTrain = null;
            TileKey blockedOnly = null;

            for (TileKey square : everyTile())
            {
                if (ui.isTrackCovered(square))
                {
                    if (onTheTrain == null && drawable(square)) onTheTrain = square;
                }
                else if (blocked.contains(square))
                {
                    if (blockedOnly == null && drawable(square)) blockedOnly = square;
                }
            }

            if (onTheTrain == null || blockedOnly == null) continue;

            TileKey free = null;

            for (TileKey square : everyTile())
            {
                if (ui.isTrackCovered(square) || blocked.contains(square)) continue;

                if (drawable(square))
                {
                    free = square;

                    break;
                }
            }

            if (free == null) continue;

            coveredSquare = onTheTrain;
            blockedSquare = blockedOnly;
            freeSquare = free;
            trainLength = length;

            return true;
        }

        return false;
    }

    private static boolean drawable(TileKey square)
    {
        org.traincontrol.base.LayoutDiagram page = model.getLayout(square.getPage());

        if (page == null) return false;

        LayoutDiagramComponent component = page.getComponent(square.getX(), square.getY());

        return component != null && !component.isText();
    }

