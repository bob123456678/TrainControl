/**
 * W7B-B1, and Adam's ruling on it - **the grey appears at idle too, and it is regenerated by the
 * gestures that change it**.
 *
 * Adam, 2026-09-09: *"yes, this greyout should appear at idle and be regenerated if a placement or
 * train/track length is changed."*
 *
 * **What the fence cost.**  The REFUSAL over a standing train's tail has never been fenced on a
 * running railway - `Layout.isPathClear` sweeps the covered edges in every tier at every time, which
 * is right, because a tail lying across the rail is a physical fact rather than a preference.  The
 * DRAWING was fenced: *"can we just grey out the tiles just like blocked edges while autonomy is
 * running?"*  So with nothing running, a right-click manual send across a parked train's tail was
 * refused over track the diagram painted as free - which is the very complaint (*"a square the
 * railway would not let a train onto looked exactly like free track"*) that brought the grey back on
 * 2026-09-09 for the running case.  The guard and the affordance have to ask one question
 * (OB-057/OB-090), and now they do.
 *
 * **Four claims, and they are different claims.**
 *
 * - The grey is THERE at idle, on a square the railway refuses and no train is drawn on.  Asserted in
 *   pixels, because whether a square is greyed is decided when the tile is PAINTED - every
 *   model-level assertion available answers identically with the grey present and absent, which is
 *   the lesson OB-180 and `support.Rendered` were written for.
 * - It is REGENERATED when a locomotive is placed or removed.
 * - It is REGENERATED when a train's length changes.
 * - It is REGENERATED when a tile's length changes.
 *
 * **The three regeneration claims drive a production door and never ask for a refresh.**  That is the
 * whole of what they are for: `support.CoveredMarks.refresh` calls the window's private recompute, so
 * a test that called it after the gesture would prove only that the recompute works - which the first
 * claim already proves.  What is under test is whether the DOOR asks.  So each gesture goes through
 * the code the operator's hand reaches, and the test only WAITS afterwards
 * (`support.CoveredMarks.settle`), because the marks are worked out on a worker (OB-192) and asking
 * and reading are two moments.
 *
 * **Which doors, and why those.**
 *
 * - Removal: `TrainControlUI.locomotiveGestureOnDiagram` with Delete, which is the diagram's own
 *   keyboard door - *"Control+X takes the locomotive off the hovered square and remembers it, Control+V
 *   puts one down, and Delete takes one off without remembering."*  Delete rather than Control+X so
 *   that nothing lands on the clipboard, and rather than Control+V so that no arrival-side dialog can
 *   open and block the test on a modal.
 * - Train length: `TrainControlUI.applyTrainLength`, which is everything `promptTrainLength` does once
 *   the dialog has answered.  The dialog itself cannot be driven from a test without a robot, and the
 *   half that matters is the half after it; `regression.testEditorSurfaceRules` pins the call site so
 *   that extracting the rule cannot leave the caller behind.
 * - Tile length: `TrainControlUI.rebuildRunningLayoutFromSetup`, which is what
 *   `AutonomyEditorPanel.setupChanged` posts after the length is written.  A tile length can only
 *   reach the marks through a rebuild - edge lengths are baked into the built `Layout`, unlike train
 *   lengths, which `Layout.edgesCoveredByStandingTrains` reads off the locomotive every time it is
 *   asked.
 *
 * **The blocked extent is worked out here from the railway rather than asked of the window**, the same
 * way `ui.testBlockedTrackIsGreyWhileAutonomyRuns` does it and for the same reason: the claim is that
 * what is drawn is what `Layout.edgesCoveredByStandingTrains` refuses, and asking the window would be
 * asking the thing under test what the right answer is.
 *
 * **Unmeasured track is how the tile-length gesture is made visible.**  Behaviour.md 5c: the tail walk
 * *"stops at unmeasured track.  Only positive lengths are determinate."*  So measuring every square as
 * one unit blocks track and measuring every square as none blocks nothing, and the difference between
 * those two is a tile-length change with everything else held still.
 *
 * MUTATION, both measured rather than reasoned:
 *
 * - Put the `isAutonomyBusy()` fence back on the blocked set in `TrainControlUI.workOutCoveredTrack`
 *   and five of the seven fail - everything except the two controls, `testFreeTrackIsNotTouchedAtIdle`
 *   and the wash-shape claim that depends on the first.
 * - Take `blockedTrackChanged()` out of `TrainControlUI.applyTrainLength` and three fail:
 *   `testATrainLengthChangeRegeneratesTheGreyAtIdle`, which is the claim, and the two pixel claims,
 *   because the reference picture - the same square with nothing standing on it - is taken through
 *   that same door and becomes a copy of the picture it is being compared with.  Worth writing down:
 *   it means the two pixel claims cannot tell that failure from the fence's, and the set-level claim
 *   is the one that names it.
 *
 * @author Adam
 */
