    @BeforeClass
    public static void setUpClass() throws Exception
    {
        if (java.awt.GraphicsEnvironment.isHeadless())
        {
            throw new SkipException("painting a tile needs a display");
        }

        // THE FROZEN COPY, NOT THE RAILWAY HE IS OPERATING (OB-111, and `test/layouts/live-snapshot`).
        //
        // `Scenario.folderFor` rather than a path: it is the only naming of a fixture folder that
        // cannot spell its way out to the operator's own railway, and `LayoutSandbox` still copies
        // what it names before anything reads it.
        sandbox = support.LayoutSandbox.open(support.Scenario.folderFor("live-snapshot"));

        model = init(null, true, true, false, true);
        model.setNetworkCommState(false);

        ui = (TrainControlUI) model.getGUI();

        assertNotNull(ui, "there is no window");

        pump();
        pump();

        session = ui.getAutonomySession();

        if (session == null) throw new SkipException("no autonomy setup on this railway");

        SwingUtilities.invokeAndWait(() -> measureEveryTileAs(1));

        model.parseAuto(session.buildConfiguration());

        layout = model.getAutoLayout();

        // THE CONFIGURATION THE REBUILD LOADS, which its first guard reads (as
        // `regression.testAPendingTurnSurvivesTheRebuild` sets it, and for the reason it gives): a
        // null makes `rebuildRunningLayoutFromSetup` a no-op, and a test whose subject silently does
        // nothing is the failure mode this repository keeps finding.
        if (ui.getActiveDiagramConfiguration() == null)
        {
            String active = session.getStore().getActiveConfiguration();

            if (active == null) throw new SkipException("the snapshot names no active configuration");

            Field field = TrainControlUI.class.getDeclaredField("activeDiagramConfiguration");

            field.setAccessible(true);
            field.set(ui, active);
        }

        // NOTHING IS RUNNING, and this class is about nothing running.  Asserted rather than assumed:
        // every claim below would be about the old, fenced behaviour if a run had somehow started.
        assertFalse(layout.isRunning(),
            "the frozen railway came up with autonomy running, so every claim here is about the wrong"
            + " state");

        oneTrainThatCoversSomething();

        if (train == null) throw new SkipException("no standing train covers any track here");

        if (!chooseTheThreeSquares())
        {
            throw new SkipException(
                "no train on this railway blocks a square it is not drawn on, so the two marks "
                + "cannot be told apart here");
        }

        coveredTile = drawnTileFor(coveredSquare);
        blockedTile = drawnTileFor(blockedSquare);
        freeTile = drawnTileFor(freeSquare);

        // AT IDLE, with the train exactly where it is.
        train.setTrainLength(trainLength);

        support.CoveredMarks.refresh(ui);

        pump();

        repaintTheThree();

        idleCovered = paint(coveredTile);
        idleBlocked = paint(blockedTile);
        idleFree = paint(freeTile);

        windowBlockedAtIdle = whatTheWindowHoldsBlocked();

        // AND AT IDLE WITH NOTHING STANDING ANYWHERE, which is the reference every "is this square
        // marked at all" question is asked against.  A length of zero is how this railway says "not
        // set", and an unmeasured train covers nothing.
        //
        // THROUGH THE DOOR, and nobody asks for a refresh afterwards: this is the train-length
        // gesture as well as the reference picture.
        SwingUtilities.invokeAndWait(() -> ui.applyTrainLength(train, 0));

        pump();

        support.CoveredMarks.settle(ui);

        windowBlockedAfterLengthZero = whatTheWindowHoldsBlocked();

        repaintTheThree();

        bareCovered = paint(coveredTile);
        bareBlocked = paint(blockedTile);
        bareFree = paint(freeTile);

        // AND BACK, so the gesture is shown in both directions - putting the wash on is the half a
        // set comparison makes easy to forget.
        SwingUtilities.invokeAndWait(() -> ui.applyTrainLength(train, trainLength));

        pump();

        support.CoveredMarks.settle(ui);

        windowBlockedAfterLengthBack = whatTheWindowHoldsBlocked();

        captureTheTileLengthGesture();

        captureTheRemovalGesture();
    }

