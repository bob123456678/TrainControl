#!/bin/bash
#
# Runs every test class, one JVM each, and reports which ones are not green.
#
# Lived in a session scratch directory until 2026-08-25, which is why the bug below could be made
# twice: a harness nobody can read is a harness nobody can review. It is here now.
#
# Usage, from the project root:
#
#     TC_SCRATCH=/path/to/scratch bash docs/tools/battery.sh
#
# LANES (FR-136 Phase 1a): TC_LANES=auto, or a number, runs the classes in that many JVMs at once, each with a data
# folder, a preference node and a temp folder of its own.  The classes in serial-lane.txt run first, alone, holding
# every test slot; then each lane holds one slot, and at least one stays free for a worker's one.sh.  TC_DURATIONS
# names a tng-run folder whose timings order the classes longest first (default: this scratch's own, from the last
# run).  Without TC_LANES the run is what it always was: one class at a time, in name order, holding every slot.
#
# DO NOT EDIT THIS FILE WHILE A RUN IS IN PROGRESS. Bash reads a script lazily, by byte offset, so an
# edit above the point it has reached shifts everything after it and the next read lands mid-token.
# The run may carry on looking healthy and produce a result that means nothing. If you need to change
# it during a long run, copy it first and run the copy - which is what a session on 2026-08-25 ended
# up doing, after editing it under a run and having to throw the run away.
#
# TC_SCRATCH holds cp.txt (the classpath, one line) and receives the TestNG output. See
# docs/manual-tests/README.md for how it is built.

set -u

S="${TC_SCRATCH:-}"

if [ -z "$S" ] || [ ! -f "$S/cp.txt" ]
then
    echo "TC_SCRATCH must name a directory containing cp.txt (the classpath)." >&2
    exit 2
fi

# NOT a stale compile directory first.  A leftover tree once shadowed the real one, so the battery
# silently tested old code and a method added minutes earlier came back as NoSuchMethodError.
CP="$(cat "$S/cp.txt")"

# AND THE BATTERY COMPILES THE WORKING TREE ITSELF, which is the other half of that sentence and was
# missing for as long as the sentence has been there.
#
# cp.txt begins with one.sh's output directory, and this script had no compile step of its own - so a
# battery reported on whatever one.sh happened to have compiled last, which is not the same thing as
# the working tree and on 2026-08-29 was not even close.  A mutation had been compiled into that
# directory to prove a test could catch it; the source was restored, the battery was run, and it
# reported the mutation's three failures against a tree that did not contain it.  Every earlier
# battery today was only as true as the last one.sh before it.
#
# The comment above was written about a stale directory SHADOWING the real one.  The failure it did
# not name is the same directory being the ONLY one, which is worse, because then there is nothing to
# shadow and no symptom to notice.
#
# Compiled into a directory of this script's own and PREPENDED, so every class the run loads is one
# this compile produced and one.sh's output cannot reach the classpath ahead of it.
#
# ONE BATTERY AT A TIME, and the directory belongs to the run.
#
# On 2026-08-29 I started a battery while another was still going. They compiled into the same fixed
# directory, so each one's `rm -rf` deleted the other's classes underneath it, and the run came back
# with twenty-seven classes reported as DID NOT RUN. Nothing was wrong with the code.
#
# That is the third defect in this harness to report a FALSE RESULT rather than an error, and they all
# have the same shape: the runner decided what a run meant while something else was changing what it
# was running.
#
# The lock is the fix - the second battery now refuses to start and says which process is already
# going. The per-run directory is the belt: if two ever do overlap despite it, a stale lock or a killed
# run, they no longer compile over each other, and the failure is slow rather than wrong.
# USER-WIDE, NOT PER-SESSION (SV2-A2).
#
# This was "$S/battery.lock", and $S is TC_SCRATCH - a directory per agent session.  So two sessions
# took two different lock files, neither ever looked at the other, and the lock could not have
# prevented a single one of the overlaps it was written for.  Every liveness fix applied to it on
# 2026-09-01 was work on the wrong mechanism.
#
# The crash dumps in the repository root are the evidence: battery-40080 ran out of
# .../0362837d-.../scratchpad/tc and battery-32945 out of .../51b92044-.../scratchpad, and they died
# seconds apart inside the same window.  Four different session ids appear across those files.
#
# TEMP is the same directory for every session of the same user, which is the scope the hazard has -
# the Java Preferences store these runs fight over is per user, not per session.  TC_LOCK overrides it
# for anyone who needs to.
# (It is slot 1 of slots.sh's SLOT_BASE now.)

# THE LOCK IS A PROXY.  THE TEST JVMS ARE THE HAZARD (2026-09-01).
#
# On 2026-09-01 two batteries ran at once anyway, with the lock in place and working as written.  The
# reason is the liveness test below: it refuses only when `kill -0` SUCCEEDS, so every answer that is
# not a clear yes - a pid held by a different shell session, a recycled pid, anything MSYS cannot see
# across process trees - falls through and starts a second run.  A guard that fails open on the
# dangerous side is not a guard, and this one failed open in exactly the case it exists for.
#
# So the pid is no longer the only question.  What is actually dangerous is a second set of test JVMs -
# they share the Java Preferences store, which is what LayoutSandbox redirects, and two runs redirecting
# it at once is how the operator's real railway was damaged on 2026-08-30.  That is a thing this script
# can LOOK FOR rather than infer, and it is true whether the other run came from a battery, from one.sh,
# from an IDE, or from somebody else's session entirely - none of which the lock can see.
#
# It also needs no clearing by hand, which is the property the comment above insists on: the check
# stops being true the moment the other JVMs exit.  Nobody has to delete anything to get past it, so
# nobody learns to delete things to get past it.
#
# IT LOOKS FOR TestNG, NOT FOR OUR OWN FLAG (SVN-A2, corrected the same day it was written).
#
# The first version matched `-Dtraincontrol.anyReceivePort`, which is a flag only this script and
# one.sh set - so it saw its own family and nothing else, while its comment claimed it caught an IDE
# run too.  `build.xml` passes no `jvmarg` at all: an `ant test` or a NetBeans run was exactly as
# invisible as before.  What every one of them does have in common is the runner itself, so that is
# what is matched, and the old flag is kept as well for anything that sets it without TestNG on the
# command line.
#
# Adam's own running application is deliberately NOT matched.  It is not a test JVM, it does not
# redirect the preference, and blocking every battery while he has the app open would be the kind of
# over-strict guard that gets deleted rather than obeyed.
# javac too (SV2-A2): a battery owns no JVM at all while it is compiling, which is precisely
# where the two runs of 2026-09-01 overlapped - both of them in javac.  Measured on this
# machine the javac process itself lives only a few seconds, not the "minute or two" an
# earlier version of this comment claimed; short is not the same as absent, and two runs
# started together land in it together.
#
# MATCHED BY THE ARGFILE, not by the project name (TV2-C1).  The first version of this asked
# for a javac whose command line contains "TrainControl", and neither runner's compile has
# that on it when cp.txt holds relative paths - which this session's does.  The measurement
# that "confirmed" it was matching the testng clause instead.  What IS always present is the
# argfile: one-files.txt or battery-files.txt.
#
# The probe and the lock below are in slots.sh now, shared with one.sh (FR-136 Phase 1a).  Before the lanes this
# run needs the machine to itself, so it counts every test JVM, as this always did.
TOOLS="$(cd "$(dirname "$0")" && pwd)"

. "$TOOLS/slots.sh"

refuse_if_test_jvms all

# AND THE LOCK IS WHAT COVERS THE COMPILE.
#
# The JVM check above cannot see a battery that has not reached its JVMs yet, and this script compiles
# the whole tree first - a minute or more in which a second run looks past it and finds nothing.  That
# is exactly the window the two concurrent batteries of 2026-09-01 overlapped in: both were in javac,
# so neither could see the other by its processes.  The lock is held from here, before the compile, so
# it is the only thing that covers that window - which makes its liveness test worth getting right.
#
# `kill -0` was the wrong test.  MSYS resolves pids within its own process tree, so a lock written by
# a shell in another session reads as dead, the guard concludes "stale" and starts a second run.  It
# has to fail open on every answer that is not a clear yes, which is the dangerous direction.
#
# Windows can answer the question that MSYS cannot, so it is asked instead - and the three outcomes are
# now distinguished rather than collapsed into two: alive refuses, dead proceeds quietly, and an
# unanswerable probe says so and proceeds, because a battery nobody can run is worse than this hazard
# and the guard above is still standing.
# AND THE LOCK MUST HOLD A PID WINDOWS HAS HEARD OF (FV2-A1, corrected within hours).
#
# The first version of this asked `Get-Process -Id` about `$$`, which is the MSYS pid - a number
# Windows does not use.  Measured on this machine: a live shell is msys 42457 / winpid 17552, and
# `Get-Process -Id 42457` answers "no" while `-Id 17552` answers "yes".  So every LIVE battery read as
# stale, the script announced "clearing a stale lock" and started a second run inside the compile
# window the lock exists to cover.  It was strictly worse than the `kill -0` it replaced.
#
# It passed its test because the test wrote a Windows pid into the lock by hand and watched the check
# refuse.  That exercised the branch with a value the script never writes - the check was verified and
# the integration was not.
#
# So the lock holds the winpid now, and liveness is "either test says alive": Get-Process for the
# Windows number, and kill -0 as well, which does work across MSYS sessions - the earlier claim that
# it does not was also wrong.  Two tests that can only ever say "still running" cannot combine into a
# false "stale", which is the only direction that costs anything here.
#
# All of it is in slots.sh now: the winpid, the namespace, the liveness test, the take and the take-over.  Every
# slot, because the compile and the serial lane need the machine to themselves; a run with lanes gives back the
# ones its lanes do not need once those are done.  Its refusals say "nothing was run", which this one's "ANOTHER
# BATTERY IS ALREADY RUNNING" did not.
take_every_slot

BUILD="$S/build/battery-$$"

# The lock and this run's classes go whichever way the script leaves - including the live-layout
# guard's exit 1, which is the one somebody is most likely to be reading when it fires, and including
# being killed.
#
# INT and TERM as well as EXIT, because a battery is usually stopped rather than waited for, and a run
# that is killed without releasing its lock blocks every later one - a guard that has to be cleared by
# hand is worse than no guard, because the first thing anybody does is delete the lock and stop
# believing in it.
# ------------------------------------------------------------------------------------------------
# ON THE WAY OUT, WHICHEVER WAY (TSX-C14).
#
# Three things the traps did not do, all of which matter most on the path they are for - a run that
# was stopped rather than waited for.
#
# THE LOCK IS RELEASED ONLY IF IT IS STILL OURS.  `rm -f "$LOCK"` never asked.  Since REL-C10 the
# unknown arm deliberately takes a live-but-unresolvable lock OVER, so two runs holding the "same"
# lock is a state this is designed for - and the first of them to finish was deleting the second's
# lock and leaving the machine unlocked with a battery still going.  REL-C9 named this sequence for
# the `mv` and the trap was not changed with it.
#
# THE REAPER RUNS.  A run stopped part way leaves the class it was on going, and reap.ps1 matches the
# run id whole while that id embeds this shell's pid - so once the shell is gone nothing can ever
# match it again.  That is the permanence argument battery.sh already writes out for its post-loop
# reap, arriving at the trap.
#
# AND THE LAYOUT IS CHECKED.  one.sh's own header states the rule: "a guard that only runs on the
# slow path is a guard that is not running."  The run most likely to have written to
# cs2_sample_layout is the one that was killed because a class hung, and that was the one run neither
# script looked at.  Only when the run did NOT reach its own report, which does this properly.
release_the_lock()
{
    release_all_slots
}

REPORTED=""

# ONCE, NOT TWICE (VD9-B2).
#
# `trap '...; exit 130' INT TERM` runs its body and then exits - and exiting fires the EXIT trap,
# which runs the same body again.  Measured, not assumed: a throwaway script with this exact pair
# prints its handler twice.  So a killed run reaped twice and, worse, printed the "this run was
# stopped and the layout changed" warning twice, which reads as two events.
DONE=""

on_the_way_out()
{
    if [ -n "${DONE:-}" ]; then return; fi

    DONE=1

    # BEFORE the fingerprint, because a leftover JVM is by definition one that is still running and
    # deferred work landing after everybody stopped watching is the whole subject of LayoutSandbox.
    #
    # Written out rather than calling reap(), and every variable defaulted - genuinely every one
    # now (VD9-C7): $LOCK, $REPORTED and $DONE were not, and under `set -u` an unbound one aborts
    # the trap at that line and takes `rm -rf "$BUILD"` with it, which is the exact failure this
    # comment claimed to be preventing.
    #
    # It could not happen, because all three are set before the trap is armed - but that is safety
    # by arming order, and this body is meant to survive being moved.
    if [ -n "${LANE_PIDS:-}" ]
    then
        kill ${LANE_PIDS:-} 2>/dev/null
    fi

    if [ -n "${REAPER:-}" ]
    then
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$REAPER"             -RunId "${RUN_ID:-}" >/dev/null 2>&1

        for id in ${LANE_IDS:-}
        do
            powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$REAPER" -RunId "$id" >/dev/null 2>&1
        done
    fi

    if [ -z "${REPORTED:-}" ] && [ -n "${live_before:-}" ]
    then
        if [ "$live_before" != "$(fingerprint)" ]
        then
            echo ""
            echo "*** THIS RUN WAS STOPPED, AND ${LIVE:-the layout} CHANGED WHILE IT RAN ***"
            echo ""
            echo "That folder is Adam's real railway.  Check it before trusting anything above, and"
            echo "check whether TrainControl was open - a running railway rewrites it as trains move."
            echo ""
        fi
    fi

    release_the_lock

    rm -rf "${BUILD:-}" "${WORK:-}"

    # AND THIS RUN'S OWN STATE, which nothing after it may read (see ISOLATED).  The node is the one
    # `Util.preferencesFor` built under traincontrol-test-runs; MSYS_NO_PATHCONV so that /f reaches
    # reg.exe as a switch rather than as a path.
    rm -rf "${ISOLATED:-}"

    if [ -n "${RUN_ID:-}" ]
    then
        MSYS_NO_PATHCONV=1 reg.exe delete "HKCU\\Software\\JavaSoft\\Prefs\\traincontrol-test-runs\\${RUN_ID}" /f \
            >/dev/null 2>&1
    fi

    # And each lane's, which are named after this run (see run_lane).
    for id in ${LANE_IDS:-}
    do
        rm -rf "${S:-}/state-$id"

        MSYS_NO_PATHCONV=1 reg.exe delete "HKCU\\Software\\JavaSoft\\Prefs\\traincontrol-test-runs\\$id" /f >/dev/null 2>&1
    done
}

LANE_PIDS=""
LANE_IDS=""
WORK=""

trap 'on_the_way_out; exit 130' INT TERM
trap 'on_the_way_out' EXIT

rm -rf "$BUILD"
mkdir -p "$BUILD"

find src test -name "*.java" > "$S/battery-files.txt"

if ! "${TC_JAVAC:-/c/Program Files/Java/jdk1.8.0_361/bin/javac}" -nowarn -encoding UTF-8 \
    -d "$BUILD" -cp "$CP" @"$S/battery-files.txt" 2>"$S/battery-javac.log"
then
    echo "*** THE WORKING TREE DOES NOT COMPILE - nothing was run ***"
    echo ""
    grep -i "error" "$S/battery-javac.log" | head -20
    exit 2
fi

CP="$BUILD;$CP"

JAVA="${TC_JAVA:-/c/Program Files/Java/jdk1.8.0_361/bin/java}"

# Any free receive port instead of the Marklin one.
#
# Every class that builds a MarklinControlStation used to bind UDP 15730, so the battery could not run
# while TrainControl was open, an orphaned JVM poisoned every class after it, and two classes could
# never overlap. None of them receives anything from a Central Station - there is none - so the port
# was pure contention.
#
# The failure it removes is a nasty one to read: a bind failure comes out of @BeforeClass as
# "Total tests run: 16, Failures: 0, Skips: 16" - zero failures, having tested nothing.
JAVA_FLAGS="${TC_JAVA_FLAGS:--Dtraincontrol.anyReceivePort=true}"

# This run's own name, so the reaper can tell this battery's leftovers from anything else on the
# machine - including another battery, and including a test somebody is running by hand.
#
# Without it the reaper matched every JVM carrying the receive-port flag, which is every test JVM
# there is: a battery running in the background killed a hand-run test at exit 127 with no output,
# which reads as the test hanging rather than as something else shooting it.
RUN_ID="battery-$$"

# WHERE THE REAPER IS, resolved once and checked (TS3-A1).
#
# Said out loud rather than swallowed: a reaper that is not there is exactly the condition that let
# four days of runs leave their JVMs behind, and the whole reason it went unnoticed is that the call
# could not fail visibly.  A run without one is still worth having, so this warns rather than refuses.
REAPER="$(cd "$(dirname "$0")" && pwd)/reap.ps1"

if [ ! -f "$REAPER" ]
then
    echo "*** WARNING: no reaper at $REAPER - leftover test JVMs will NOT be cleaned up ***"
    echo ""
    echo "A JVM left behind by one class poisons every class after it, and trips the next run's"
    echo "start-of-run probe with a message that says the check clears itself.  It will not."
    echo ""

    REAPER=""
fi

# The lanes' flags are these less the run's own name, which each lane has one of (FR-136 Phase 1a).
LANE_FLAGS="$JAVA_FLAGS"

JAVA_FLAGS="$JAVA_FLAGS -Dtraincontrol.batteryRun=$RUN_ID"

# A BOUNDED HEAP, because an unbounded one asks for a quarter of the machine per class.
#
# A default-heap JVM reserves a fraction of physical RAM up front. With NetBeans open and Adam running
# his own tests, three classes in battery34 could not get it, died before TestNG loaded, and were
# reported as DID NOT RUN - the same wording as a class that crashed, so the run looked like it had
# three faults in it and had none. All three passed in 512m; the bound is 768m since the window
# classes outgrew it (below).
#
# Overridable, because the number is a guess about this machine rather than a property of the tests.
# 768m SINCE 2026-09-30: regression.testTheImportDoorReadsAnOldFile - 41 window tests on the live snapshot, each keeping its
# thread pools - ran out of 512m in battery r28, having fitted the round before.  A window class grows by a claim a round.
JAVA_FLAGS="$JAVA_FLAGS ${TC_JAVA_HEAP:--Xmx768m}"

# AND OUT, NOT STUCK, WHEN IT RUNS OUT (2026-09-29).  A class that filled its heap - every window a test opens keeps its
# threads - lost TestNG's main thread in the report, with the error on the stderr the application swallows and no summary
# printed; the JVM then sat on its pool threads until the class cap, an hour.  Exiting on the error ends it at once, and
# the branch that reads a missing summary says it ran out.
JAVA_FLAGS="$JAVA_FLAGS -XX:+ExitOnOutOfMemoryError"

LANE_FLAGS="$LANE_FLAGS ${TC_JAVA_HEAP:--Xmx768m} -XX:+ExitOnOutOfMemoryError"

# ------------------------------------------------------------------------------------------------
# THIS RUN'S OWN STATE: copies of the locomotive database and the UI state, and a preference node of
# its own.
#
# Adam, 2026-09-23: *"does my app really have to stay closed? I thought the battery got isolated
# earlier"* - and it had not been.  Every test JVM read and wrote the working directory's LocDB.data
# and UIState.data, and the machine-wide preference node his running application uses; LayoutSandbox
# points that node's layout path at a sandbox for the length of a class, which his application would
# read if it started meanwhile.  Test JVMs sharing that state with a live one threw points under a
# real train on 2026-08-30.
#
# So each run copies the two data files into a folder of its own and names a preference node of its
# own, and the application reads both from there when a run says so (`Util.dataPath`,
# `Util.preferencesFor`; with neither property set it reads what it always read).  The node starts as
# a copy of the real one, so a class sees the settings it always saw; nothing the run writes reaches
# the real node or the real files.  Both are removed when the run ends.
#
# The short (8.3) form of the folder, because $JAVA_FLAGS is split on spaces.
ISOLATED="$S/state-$RUN_ID"

rm -rf "$ISOLATED"
mkdir -p "$ISOLATED"

for DATA in LocDB.data UIState.data
do
    if [ -f "$DATA" ]; then cp "$DATA" "$ISOLATED/"; fi
done

JAVA_FLAGS="$JAVA_FLAGS -Dtraincontrol.dataDir=$(cygpath -ws "$ISOLATED") -Dtraincontrol.preferences=$RUN_ID"

# HOW MANY LANES (FR-136 Phase 1a).  None unless asked for, until the laned battery has been compared with this one
# claim by claim.  "auto" takes one per four logical processors and one per free gigabyte past a reserve of one and a
# half - a window class's JVM grows to about a gigabyte in its 768m heap - and always leaves one slot for a worker.
LANES="${TC_LANES:-1}"

case "$LANES" in
    auto)
        by_cpu=$(( $(nproc 2>/dev/null || echo 4) / 4 ))
        free_mb=$(( $(awk '/^MemFree/ { print $2 }' /proc/meminfo 2>/dev/null || echo 0) / 1024 ))
        by_memory=$(( (free_mb - 1536) / 1024 ))

        LANES=$by_cpu
        [ "$by_memory" -lt "$LANES" ] && LANES=$by_memory

        echo "lanes: auto - $(nproc 2>/dev/null) logical processors, $free_mb MB free"
        ;;
    ''|*[!0-9]*)
        echo "TC_LANES must be a number or auto, not '$LANES'." >&2
        exit 2
        ;;
esac

if [ "$LANES" -gt $((SLOTS - 1)) ]
then
    echo "lanes: $LANES asked for, $((SLOTS - 1)) given - one of the $SLOTS test slots stays free for a worker's run"

    LANES=$((SLOTS - 1))
fi

[ "$LANES" -lt 1 ] && LANES=1

if [ "$LANES" -gt 1 ]
then
    echo "lanes: $LANES, after the serial lane ($SLOTS test slots on this machine)"
    echo ""

    # A temp folder of its own as well (see one.sh): LayoutSandbox keeps its repair marker under a fixed name there.
    mkdir -p "$ISOLATED/tmp"

    JAVA_FLAGS="$JAVA_FLAGS -Djava.io.tmpdir=$(cygpath -ws "$ISOLATED/tmp")\\"
fi

# Adam's own railway, hashed before and after the whole run.
#
# A test class can watch its OWN writes - testTheGoldenLayoutHoldsTogether does - but not
# another class's, and the write that actually happened came from a class that had no idea it
# was near his layout: two of them start the real window, which opens whatever the saved UI
# state names.
#
# It went unnoticed for two days.  This is the scope that would have caught it on the first run.
LIVE="cs2_sample_layout"

fingerprint()
{
    if [ -d "$LIVE" ]
    then
        # Carriage returns stripped before hashing.
        #
        # Git checks these files out with CRLF and the application writes them with LF, so a
        # file rewritten with identical content still differs byte for byte.  Reporting that
        # would make this guard fire on every run, and a guard that always fires is one nobody
        # reads - which is the failure this whole check exists to prevent, arriving from the
        # other side.
        find "$LIVE" -type f -print0 2>/dev/null | sort -z | while IFS= read -r -d "" f
        do
            printf "%s  %s\n" "$(tr -d "\r" < "$f" | sha256sum | cut -d" " -f1)" "$f"
        done
    fi
}

live_before=$(fingerprint)

# AND THE SOURCE THIS RUN IS MEASURING (E8V-C5).
#
# Forty-four classes in this battery read `src/` and `test/` FROM DISK while they run, rather than
# through the bytecode the compile above produced: the citation roll, the battery-membership census,
# the event-thread door census, the editor surface rules, the shortcut census, the javadoc checks.
#
# So a battery is a measurement of ONE COMMIT only while nobody edits the tree - and when somebody
# does, what comes out is a failure in a source-scanning class carrying a message about its own
# subject.  A validation pass lost time to exactly that: the citation roll failed naming five
# identifiers that did not exist when the run began, and the way to find out why was to read the diff
# of a tree that had moved rather than anything this runner printed.
#
# Names and sizes rather than content hashes.  What matters is "did the tree move", the two directories
# hold several thousand files, and hashing them all would add real time to every run for a question a
# cheap answer settles.
sourceprint()
{
    for tree in src test build.xml
    do
        if [ -e "$tree" ]
        then
            find "$tree" -type f -printf "%p %s\n" 2>/dev/null | sort
        fi
    done
}

source_before=$(sourceprint)

# ------------------------------------------------------------------------------------------------
# ONE CLASS, IN THE JVM IT IS GIVEN (FR-136 Phase 1a): $1 is the run's name, the reaper's key; $2 its flags; $3 the
# class.  The loop body this always was, made a function so a lane can run it; its verdict goes to a file rather than
# into the counters, because a lane is a subshell whose variables die with it.
WORK="$S/build/battery-$$-work"

rm -rf "$WORK"
mkdir -p "$WORK/verdicts" "$WORK/claims"

verdict()
{
    printf "%s\n%s\n" "$1" "$2" > "$WORK/verdicts/$cls"
}

run_class()
{
    local cls="$3"

    # Only THIS RUN's leftover JVMs - reap.ps1 says why that is narrower than "every test JVM", and
    # narrower again than "every java.exe".
    #
    # FROM THE SCRIPT'S OWN DIRECTORY, not from the working directory (TS3-A1).
    #
    # This read "$(pwd)/tools/reap.ps1" from 2026-08-25 until 2026-09-02, and the file has been at
    # docs/tools/reap.ps1 since fb3722f5 moved the folder on 2026-08-30 - a commit whose message says
    # "all eleven referring files repointed" and which missed this one, the script's call to its own
    # sibling.  With the error going to /dev/null, every battery for four days reaped nothing and said
    # nothing about it.
    if [ -n "$REAPER" ]
    then
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$REAPER" \
            -RunId "$1" >/dev/null 2>&1
    fi

    # The WHOLE output, not its last few lines (found 2026-08-25).
    #
    # This was `| tail -4`, and it turned a green class into "DID NOT RUN". TestNG prints its summary
    # and then anything the JVM still has to say - and core.testAutonomySimulationSanity ends with a
    # Marklin packet dump from a socket timing out, so the summary had scrolled past by line four.
    #
    # That is the third harness defect in this round that reported a false result rather than an
    # error, and they all have the same shape: the runner decided what a run meant by looking at part
    # of it. It is cheap to read all of it.
    # WATCHED, NOT WAITED FOR (2026-09-29).  A JVM that has printed TestNG's summary and does not exit - a window or a
    # thread a test left behind - held this loop, the machine and every later run for nine hours on 2026-09-28, and the
    # reap that would have ended it never ran, because the loop never got there.  So the JVM runs in the background and
    # is watched: once its summary is out it has TC_HANG_GRACE seconds to exit (120 by default), and it has TC_CLASS_CAP
    # seconds in all (3600); past either, this run's own JVMs are reaped and the class is reported as HUNG - a class
    # that leaves something running is not a green class, whatever its summary says.
    RUN_OUT="$S/tng-run/$cls.out"

    mkdir -p "$S/tng-run"

    "$JAVA" $2 -cp "$CP" org.testng.TestNG -testclass "$cls" -d "$S/tng-run/$cls" > "$RUN_OUT" 2>&1 &

    local JVM=$!

    HUNG=""
    started=$(date +%s)
    summarised=""

    while kill -0 "$JVM" 2>/dev/null
    do
        sleep 2

        now=$(date +%s)

        if [ -z "$summarised" ] && grep -q "Total tests run" "$RUN_OUT" 2>/dev/null; then summarised=$now; fi

        if [ -n "$summarised" ] && [ $((now - summarised)) -ge "${TC_HANG_GRACE:-120}" ]
        then
            HUNG="its JVM did not exit ${TC_HANG_GRACE:-120} s after its summary"

            break
        fi

        if [ $((now - started)) -ge "${TC_CLASS_CAP:-3600}" ]
        then
            HUNG="its JVM was still running after ${TC_CLASS_CAP:-3600} s"

            break
        fi
    done

    if [ -n "$HUNG" ]
    then
        if [ -n "$REAPER" ]
        then
            powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$REAPER" \
                -RunId "$1" >/dev/null 2>&1
        fi

        kill -9 "$JVM" 2>/dev/null
    fi

    wait "$JVM" 2>/dev/null

    out=$(cat "$RUN_OUT" 2>/dev/null)

    if [ -n "$HUNG" ]
    then
        verdict fail "$cls: HUNG - $HUNG; this run's JVMs were ended"

        return
    fi

    # The LAST one, because a class can print the word before it finishes - and the last summary is
    # the one that describes the whole run.
    summary=$(echo "$out" | grep 'Total tests run' | tail -1)

    # TestNG's summary is TWO lines, and this read one (found 2026-08-25, by review).
    #
    #     Total tests run: 1, Failures: 0, Skips: 0
    #     Configuration Failures: 1, Skips: 0
    #
    # A class whose @AfterClass throws prints exactly that, and the first line alone says green.  The
    # teardowns in this suite are load-bearing: testBothProtectingSignalsAreThrown puts two of Adam's
    # real signals back to GREEN in its teardown and says why, and testARouteDoesNotThrowSwitchesUnderATrain
    # clears the auto layout in its own.  A teardown that threw would leave the railway changed and be
    # reported as a clean run.
    configFailures=$(echo "$out" | grep 'Configuration Failures' | tail -1)

    if [ -z "$summary" ]
    then
        # A class that produced no summary did not run.  Reported as a failure on purpose: a runner
        # that reads only "Failures:" calls a class that never started clean.
        # SAY WHICH KIND, because the two need opposite responses.  A JVM that could not reserve
        # its heap is the machine being busy, and the answer is to run it again; anything else is the
        # class, and the answer is to go and read it.  They read identically before this, which cost a
        # round of hunting for a fault in three classes that were fine.
        # BOTH WORDINGS, and neither is the one this first grepped for.  A 64-bit JDK 8 says
        # "Unable to allocate NNN bitmaps ... for the requested NNNKB heap" when -Xmx cannot be met,
        # and its other reservation message embeds the size - "Could not reserve enough space for
        # %I64uKB object heap" - so matching the bare sentence matched neither, and the branch was
        # dead for the very incident it was written for.
        if echo "$out" | grep -qE "Could not reserve enough space|Unable to allocate.*heap"
        then
            verdict fail "$cls: DID NOT RUN - no heap (machine busy, rerun)"
        elif echo "$out" | grep -q "OutOfMemoryError"
        then
            verdict fail "$cls: RAN OUT OF MEMORY - split the class, or raise TC_JAVA_HEAP"
        else
            verdict fail "$cls: DID NOT RUN"
        fi

    elif ! echo "$summary" | grep -q "Failures: 0"
    then
        verdict fail "$cls: $summary"

    elif [ -n "$configFailures" ] && ! echo "$configFailures" | grep -q "Configuration Failures: 0"
    then
        verdict fail "$cls: $summary / $configFailures"

    elif echo "$summary" | grep -q "Total tests run: 0"
    then
        # ZERO tests is not zero failures (found 2026-08-25, by review).
        #
        # The skip fix below catches "Skips: N".  A class that discovers no tests at all prints
        # "Total tests run: 0, Failures: 0, Skips: 0", which satisfies both of those and landed in the
        # pass branch - so support/CS3TestServer.java and support/TestStationAddress.java, which hold
        # no tests, were counted among the green on every run.  The number was inflated by two.
        #
        # The same shape catches a class that has lost its @Test annotations, or was disabled for
        # debugging and never restored.  Counted with the skips rather than as a failure, for the same
        # reason: it needs looking at, not alarming about.
        verdict skip "$cls: $summary (no tests in this class)"

    elif echo "$summary" | grep -q "Skips: 0"
    then
        verdict pass "$cls"

    else
        # GREEN IS NOT "no failures" (found 2026-08-25).
        #
        # A class whose @BeforeClass throws reports every one of its tests as SKIPPED and none as
        # failed, so "Failures: 0" was true of a class that had tested nothing at all.
        # core.testAutonomyDiagramSampleLayout sat like that - 13 tests, 0 passed, 13 skipped -
        # and every battery in this session counted it among the green.  The stale coordinate that
        # broke it went in with the fixture separation and nothing said a word for two days.
        #
        # Counted apart rather than as a failure, because a skip can be legitimate: several
        # classes need a display and say so.  The point is that it must not read as "fine".
        verdict skip "$cls: $summary"
    fi
}

# THE CLASSES, in name order.  The filters say why each one left out is left out.
list_classes()
{
    for f in $(find test -name "*.java" | sort)
    do
        cls=$(echo "$f" | sed 's|^test/||; s|\.java$||; s|/|.|g')

        case "$cls" in *.*) ;; *) continue;; esac

        # Skipped for the reason build.xml gives: it "probes the network for a real Central Station at a
        # hardcoded address" and blocks until that answers. It hung this runner for fourteen minutes.
        case "$cls" in *testAutoDetect) echo "SKIP $cls (needs a Central Station)" >&2; continue;; esac

        # THE HELPERS ARE NOT TESTS, and counting them taught the reader to ignore the line.
        #
        # `support/` holds CS3TestServer, LayoutSandbox and TestStationAddress - a fake station, the
        # preference redirect that keeps tests off Adam's railway, and an address helper.  None has a
        # @Test, so every run ended "classes that tested nothing: 3" and that number was never zero.
        #
        # A count that is always three is not a signal.  The check exists to catch a class whose
        # @BeforeClass threw - which reports every test skipped and none failed - and a reader who has
        # learned that the last line always says three will not see the four.  `build.xml` already says
        # TestStationAddress is "a helper rather than a test"; this is the same statement, made where the
        # counting happens.
        case "$cls" in support.*) continue;; esac

        echo "$cls"
    done
}

