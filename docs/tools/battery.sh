# ------------------------------------------------------------------------------------------------
# ONE LANE (FR-136 Phase 1a): a subshell that takes the next unclaimed class from the queue until there is none.
#
# Its own name - this run's with the lane's number - so the reaper ends only its JVMs; its own copies of the two data
# files, its own preference node, and its own temp folder.  A claim is a `mkdir`, which exactly one lane can win.
# Lane 1 runs in slot 1 and the others in theirs; each but the first gives its slot back when the queue is empty,
# so a worker's run can start while the last classes finish.
run_lane()
{
    trap - EXIT INT TERM

    local k="$1"
    local id="$RUN_ID-lane$k"
    local state="$S/state-$id"

    rm -rf "$state"
    mkdir -p "$state/tmp"

    for DATA in LocDB.data UIState.data
    do
        if [ -f "$DATA" ]; then cp "$DATA" "$state/"; fi
    done

    local flags="$LANE_FLAGS -Dtraincontrol.batteryRun=$id -Dtraincontrol.dataDir=$(cygpath -ws "$state")"
    flags="$flags -Dtraincontrol.preferences=$id -Djava.io.tmpdir=$(cygpath -ws "$state/tmp")\\"

    local total
    total=$(wc -l < "$WORK/queue")

    local i=1

    while [ "$i" -le "$total" ]
    do
        if mkdir "$WORK/claims/$i" 2>/dev/null
        then
            run_class "$id" "$flags" "$(sed -n "${i}p" "$WORK/queue")"
        fi

        i=$((i + 1))
    done

    if [ -n "$REAPER" ]
    then
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$REAPER" -RunId "$id" >/dev/null 2>&1
    fi

    if [ "$k" -gt 1 ]
    then
        release_lock_file "$(slot_file "$k")"
    fi
}

if [ "$LANES" -le 1 ]
then
    # ONE CLASS AT A TIME, in name order, as it always was.
    for cls in $(cat "$WORK/classes")
    do
        run_class "$RUN_ID" "$JAVA_FLAGS" "$cls"
    done
else
    # THE SERIAL LANE FIRST, while this run still holds every slot: the classes that need the keyboard focus or the
    # clipboard, one at a time and alone.
    SERIAL_LANE=$(serial_lane_classes)

    : > "$WORK/rest"

    for cls in $(cat "$WORK/classes")
    do
        if echo "$SERIAL_LANE" | grep -qxF "$cls"
        then
            echo "serial lane: $cls"

            run_class "$RUN_ID" "$JAVA_FLAGS" "$cls"
        else
            echo "$cls" >> "$WORK/rest"
        fi
    done

    for listed in $SERIAL_LANE
    do
        grep -qxF "$listed" "$WORK/every" || echo "*** WARNING: serial-lane.txt names $listed, which is not a test class here ***"
    done

    # Then the slots the lanes do not need go back, for workers' runs.
    k=$((LANES + 1))

    while [ "$k" -le "$SLOTS" ]
    do
        release_slot "$k"

        k=$((k + 1))
    done

    # LONGEST FIRST, by the last run's timings, so the long classes do not all land at the end of one lane.  A class
    # with no timing goes first: it may be new, and it may be long.
    DURATIONS="${TC_DURATIONS:-$S/tng-run}"

    grep -o -m1 'duration-ms="[0-9]*"' "$DURATIONS"/*/testng-results.xml 2>/dev/null \
        | sed 's|^.*/\([^/]*\)/testng-results.xml:duration-ms="\([0-9]*\)"$|\1 \2|' > "$WORK/timings"

    awk 'FILENAME == ARGV[1] { ms[$1] = $2; next } { print (($1 in ms) ? ms[$1] : 999999999), $1 }' \
        "$WORK/timings" "$WORK/rest" | sort -k1,1nr -k2,2 | awk '{ print $2 }' > "$WORK/queue"

    echo "lanes: $(wc -l < "$WORK/queue") classes, $(wc -l < "$WORK/timings") timings from $DURATIONS"

    k=1

    while [ "$k" -le "$LANES" ]
    do
        LANE_IDS="$LANE_IDS $RUN_ID-lane$k"

        run_lane "$k" &

        LANE_PIDS="$LANE_PIDS $!"

        k=$((k + 1))
    done

    wait $LANE_PIDS

    LANE_PIDS=""
fi

